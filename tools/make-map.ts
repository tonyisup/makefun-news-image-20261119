// tools/make-map.ts: project Natural Earth's 110m land outlines (public domain,
// naturalearthdata.com) to one SVG path for the layouts' locator map.
//
//   node tools/make-map.ts [data/ne_110m_land.geojson]  ->  design/world.js
//
// Equirectangular, cropped to latitudes 75N..56S (Antarctica and the high Arctic carry
// no stories). x = lon + 180 (0..360), y = 75 - lat (0..131), so window.WORLD_VIEWBOX is
// "0 0 360 131" and a story at (lat, lon) sits at (lon + 180, 75 - lat). Coordinates are
// rounded to 0.5 degree and consecutive duplicates dropped, which keeps the file small.
// Node 22, standard library only.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';

const ROOT = resolve(dirname(new URL(import.meta.url).pathname), '..');
const src = resolve(ROOT, process.argv[2] || 'data/ne_110m_land.geojson');
const TOP = 75;
const BOTTOM = -56;
const geo = JSON.parse(readFileSync(src, 'utf8'));

const r = (v) => Math.round(v * 2) / 2;
const parts = [];
for (const f of geo.features) {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) {
    const ring = poly[0]; // outer ring only: at this scale lakes are noise
    const pts = [];
    for (const [lon, lat] of ring) {
      const p = [r(lon + 180), r(TOP - Math.max(BOTTOM, Math.min(TOP, lat)))];
      const last = pts[pts.length - 1];
      if (!last || last[0] !== p[0] || last[1] !== p[1]) pts.push(p);
    }
    if (pts.length < 4) continue;
    if (pts.every((p) => p[1] === TOP - BOTTOM)) continue; // wholly below the crop
    parts.push('M' + pts.map((p) => `${p[0]} ${p[1]}`).join('L') + 'Z');
  }
}
const out = resolve(ROOT, 'design/world.js');
writeFileSync(
  out,
  `// Generated by tools/make-map.ts from Natural Earth 110m land (public domain). Do not edit.\n` +
    `window.WORLD_VIEWBOX = '0 0 360 ${TOP - BOTTOM}';\n` +
    `window.WORLD_PATH = '${parts.join('')}';\n`,
);
console.log(`${out}: ${parts.length} polygons, ${readFileSync(out).length} bytes`);
